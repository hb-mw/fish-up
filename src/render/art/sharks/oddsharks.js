// ── Goblin shark (Mitsukurina owstoni): blade snout, catapult jaws, flabby pink body ───────────────
function goblinSkin(g, res, v, P) {
  // translucent pink skin: faint blood vessels, soft folds
  if (lod(res) < 1) return;
  const r = rngFor('gob' + v);
  for (let i = 0; i < 14; i++) {
    const x = 0.36 - r.next() * 0.66, f = 0.2 + r.next() * 0.55;
    const y = P.at(x, f), l = 0.02 + r.next() * 0.04, a = (r.next() - 0.5) * 1.2;
    softStroke(g, res, 0.0015, 'rgba(150,60,72,0.22)', 0.0018, (q) => {
      q.moveTo(x, y);
      q.quadraticCurveTo(x - l * 0.5, y + Math.sin(a) * l * 0.5 + 0.004, x - l, y + Math.sin(a) * l);
    });
  }
  for (let i = 0; i < 4; i++) {
    const x = 0.2 - i * 0.12;
    softStroke(g, res, 0.004, 'rgba(120,70,80,0.12)', 0.006, (q) => {
      q.moveTo(x, P.at(x, 0.62));
      q.quadraticCurveTo(x - 0.02, P.at(x, 0.8), x - 0.01, P.at(x, 0.95));
    });
  }
}

