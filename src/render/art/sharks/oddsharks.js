// ── Great hammerhead (Sphyrna mokarran) ─────────────────────────────────────────────────────────
// A pure side view would hide the hammer (it is flat and points at the camera), so the cephalofoil is drawn
// in a slight 3/4 top view: the near lobe drops toward the viewer, the far lobe rises behind — eyes at the tips.
const HAMMER = [
  [0.44, -0.03, 1], [0.455, -0.056], [0.472, -0.079], [0.484, -0.092], [0.494, -0.089], [0.498, -0.06], [0.498, -0.02], [0.495, -0.004, 1],
  [0.498, 0.012], [0.499, 0.05], [0.496, 0.083], [0.486, 0.093], [0.474, 0.083], [0.458, 0.057], [0.444, 0.024, 1],
];
const FRONT_EDGE = [[0.484, -0.092], [0.494, -0.089], [0.498, -0.06], [0.498, -0.02], [0.495, -0.004], [0.498, 0.012], [0.499, 0.05], [0.496, 0.083], [0.486, 0.093]];

function cephalofoil(g, res, v, P, S, api) {
  // contact shadow where the hammer meets the head
  soft(g, res, 0.01, 'rgba(20,22,18,0.3)', (q) => q.ellipse(0.438, 0, 0.01, 0.05, 0, 0, TAU));
  g.save();
  g.beginPath();
  shape(g, HAMMER);
  const gr = g.createLinearGradient(0, -0.1, 0, 0.1);
  gr.addColorStop(0, '#68634f');
  gr.addColorStop(0.5, '#7f7964');
  gr.addColorStop(1, '#6c6754');
  g.fillStyle = gr;
  g.fill();
  g.clip();
  // the top surface catches the light toward its leading edge; darker toward the neck
  soft(g, res, 0.012, 'rgba(50,48,40,0.4)', (q) => q.ellipse(0.436, 0, 0.016, 0.085, 0, 0, TAU));
  soft(g, res, 0.008, 'rgba(240,236,220,0.22)', (q) => {
    spline(q, FRONT_EDGE.map((p) => [p[0] - 0.008, p[1]]), true);
    q.lineTo(0.45, 0.1);
    q.lineTo(0.45, -0.1);
    q.closePath();
  });
  // near lobe: a sliver of the pale underside shows along its front edge (we look down at it)
  soft(g, res, 0.003, 'rgba(226,224,212,0.55)', (q) => {
    q.moveTo(0.5, 0.02);
    q.quadraticCurveTo(0.503, 0.07, 0.484, 0.099);
    q.lineTo(0.476, 0.093);
    q.quadraticCurveTo(0.492, 0.065, 0.492, 0.02);
    q.closePath();
  });
  texture(g, 'mottle', 0.3, 0.12, { x0: 0.42, y0: -0.11, x1: 0.51, y1: 0.11 });
  g.restore();
  softStroke(g, res, 0.002, 'rgba(250,248,236,0.3)', 0.0022, (q) => spline(q, FRONT_EDGE.slice(0, 5), true));
  // nostril grooves along the front edge, near each lobe
  if (lod(res) >= 1) {
    for (const [y0, y1] of [[-0.075, -0.06], [0.06, 0.075]]) {
      softStroke(g, res, 0.0015, 'rgba(30,28,22,0.5)', 0.002, (q) => {
        q.moveTo(0.494, y0);
        q.quadraticCurveTo(0.49, (y0 + y1) / 2, 0.494, y1);
      });
    }
  }
  api.paintEyeAt(0.487, -0.084, 0.0055, { look: { x: 0.2, y: -0.2 } });
  api.paintEyeAt(0.489, 0.083, 0.0072, { look: { x: 0.3, y: 0.25 } });
}

