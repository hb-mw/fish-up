// ── Leopard shark (Triakis semifasciata): slender, bronze-silver with dark saddles and spots ───────────
function saddles(g, res, v, P) {
  const r = rngFor('leo' + v);
  const ink = 'rgba(36,32,28,0.88)';
  for (let i = 0; i < 13; i++) {
    const xc = 0.37 - i * 0.06 + (r.next() - 0.5) * 0.012;
    if (xc < -0.35) break;
    const w = 0.024 * (1.05 - i * 0.035) * (0.8 + r.next() * 0.4);
    const depth = 0.4 + r.next() * 0.14;
    soft(g, res, 0.003, ink, (q) => {
      q.moveTo(xc + w * 0.65, P.at(xc + w * 0.65, -0.3));
      q.lineTo(xc + w * 0.6, P.at(xc + w * 0.6, 0.08));
      q.quadraticCurveTo(xc + w * 0.45, P.at(xc, depth * 0.85), xc - w * 0.15, P.at(xc - w * 0.15, depth));
      q.quadraticCurveTo(xc - w * 0.7, P.at(xc, depth * 0.75), xc - w * 0.65, P.at(xc - w * 0.65, 0.08));
      q.lineTo(xc - w * 0.7, P.at(xc - w * 0.7, -0.3));
      q.closePath();
    });
    // big adults: saddles split around a paler centre
    if (i > 1 && i < 10 && r.next() < 0.55) {
      soft(g, res, 0.003, 'rgba(160,150,128,0.5)', (q) => q.ellipse(xc, P.at(xc, 0.16), w * 0.18, w * 0.55, 0, 0, TAU));
    }
    // round spots on the flank between saddles
    const sx = xc - 0.03 + (r.next() - 0.5) * 0.008;
    if (sx > -0.33 && sx < 0.35) {
      const rr = 0.006 + r.next() * 0.004;
      soft(g, res, 0.0025, ink, (q) => q.ellipse(sx, P.at(sx, 0.5 + r.next() * 0.12), rr * 1.2, rr, 0, 0, TAU));
    }
    if (r.next() < 0.5 && sx > -0.3) soft(g, res, 0.0025, ink, (q) => q.ellipse(xc + 0.004, P.at(xc, 0.62), 0.005, 0.0045, 0, 0, TAU));
  }
}
const finSpots = (list) => (g, res) => list.forEach(([x, y, r]) => soft(g, res, 0.002, 'rgba(36,32,28,0.85)', (q) => q.ellipse(x, y, r, r * 0.85, 0, 0, TAU)));

